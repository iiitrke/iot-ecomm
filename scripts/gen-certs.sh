#!/usr/bin/env bash
# Generates a private CA and every certificate the system needs:
#   - Kafka broker keystore/truststore (SSL listener, client auth required)
#   - Backend Kafka client keystore (mutual TLS to Kafka)
#   - Backend HTTPS server keystore (what the ESP32 connects to)
#   - firmware/include/ca_cert.h (CA the ESP32 pins to)
#
# Usage: ./scripts/gen-certs.sh [backend-hostname] [backend-lan-ip]
#   backend-hostname  DNS name the ESP32 uses for the backend (default: iotecomm.local)
#   backend-lan-ip    LAN IP of the machine running the backend (default: auto-detected)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/certs"
PASS="${CERT_PASSWORD:-changeit}"
HOST_NAME="${1:-iotecomm.local}"
HOST_IP="${2:-$( (ipconfig getifaddr en0 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}') || true)}"
HOST_IP="${HOST_IP:-127.0.0.1}"
DAYS=825

rm -rf "$OUT"
mkdir -p "$OUT/ca" "$OUT/kafka" "$OUT/backend"
cd "$OUT"

echo ">> Backend HTTPS cert will be valid for: DNS:$HOST_NAME, DNS:localhost, IP:$HOST_IP, IP:127.0.0.1"

# ---------- CA ----------
openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
  -keyout ca/ca.key -out ca/ca.crt -subj "/CN=IoTEcomm Root CA/O=IoTEcomm" 2>/dev/null

# sign_cert <name> <CN> <subjectAltName> <extendedKeyUsage>
sign_cert() {
  local name="$1" cn="$2" san="$3" eku="$4"
  openssl req -newkey rsa:2048 -nodes -sha256 -keyout "ca/$name.key" -out "ca/$name.csr" \
    -subj "/CN=$cn/O=IoTEcomm" 2>/dev/null
  cat > "ca/$name.ext" <<EOF
basicConstraints=CA:FALSE
keyUsage=digitalSignature,keyEncipherment
extendedKeyUsage=$eku
subjectAltName=$san
EOF
  openssl x509 -req -in "ca/$name.csr" -CA ca/ca.crt -CAkey ca/ca.key -CAcreateserial \
    -out "ca/$name.crt" -days "$DAYS" -sha256 -extfile "ca/$name.ext" 2>/dev/null
  openssl pkcs12 -export -in "ca/$name.crt" -inkey "ca/$name.key" -certfile ca/ca.crt \
    -name "$name" -out "ca/$name.p12" -passout "pass:$PASS"
}

# ---------- Kafka broker ----------
sign_cert kafka-broker kafka "DNS:kafka,DNS:localhost,IP:127.0.0.1" "serverAuth,clientAuth"
keytool -importkeystore -noprompt \
  -srckeystore ca/kafka-broker.p12 -srcstoretype PKCS12 -srcstorepass "$PASS" \
  -destkeystore kafka/kafka.keystore.jks -deststoretype JKS -deststorepass "$PASS" -destkeypass "$PASS" 2>/dev/null
keytool -importcert -noprompt -alias ca -file ca/ca.crt \
  -keystore kafka/kafka.truststore.jks -storetype JKS -storepass "$PASS" >/dev/null
echo "$PASS" > kafka/kafka_keystore_creds
echo "$PASS" > kafka/kafka_ssl_key_creds
echo "$PASS" > kafka/kafka_truststore_creds

# ---------- Backend: Kafka client (mTLS) ----------
sign_cert backend-kafka iotecomm-backend "DNS:iotecomm-backend" "clientAuth"
cp ca/backend-kafka.p12 backend/backend-kafka.p12
cp kafka/kafka.truststore.jks backend/kafka.truststore.jks

# ---------- Backend: HTTPS server (ESP32 -> backend) ----------
# The IP is also listed as a DNS entry: the ESP32's mbedTLS matches the URL host against DNS SANs only,
# so this lets the device connect by IP while curl/browsers use the IP SAN.
sign_cert backend-https "$HOST_NAME" "DNS:$HOST_NAME,DNS:localhost,DNS:backend,DNS:$HOST_IP,IP:$HOST_IP,IP:127.0.0.1" "serverAuth"
cp ca/backend-https.p12 backend/backend-https.p12

chmod 644 kafka/* backend/*

# ---------- ESP32 CA header ----------
{
  echo "// AUTO-GENERATED by scripts/gen-certs.sh - do not edit."
  echo "// Root CA the ESP32 uses to verify the backend HTTPS certificate."
  echo "#pragma once"
  echo "static const char ROOT_CA_PEM[] = R\"PEM("
  cat ca/ca.crt
  echo ")PEM\";"
} > "$ROOT/firmware/include/ca_cert.h"

echo ">> Done."
echo "   certs/kafka/    -> mounted into the Kafka container"
echo "   certs/backend/  -> used by the Spring Boot backend"
echo "   firmware/include/ca_cert.h -> compiled into the ESP32 firmware"
